#include <stdio.h>
#include <stdlib.h>
#include "type.h"
#include "y.tab.h" 

/* External variables */
extern int syntax_err;
extern A_NODE *root;
extern FILE *yyin; // Lexer input file

/* Function prototypes from other files */
void initialize(); // From A4.c [cite: 86]
void print_ast();  // From A5.c [cite: 149]
int yyparse();     // Parser function generated by Yacc

/**
 * @brief Main driver for the parser.
 * * Takes a source file as a command-line argument,
 * initializes the parser, runs the parser, and
 * prints the Abstract Syntax Tree (AST) if parsing is successful.
 */
void main(int argc, char *argv[]) 
{
    if (argc > 1) {
        // Open the source file for reading
        if ((yyin = fopen(argv[1], "r")) == NULL) { 
            fprintf(stderr, "Error: Can not open file %s\n", argv[1]);
            exit(1); 
        }
        printf("Start Syntax Analysis from file: %s\n\n", argv[1]);
    }
    // (./syntax only)
    else {
        printf("Start Syntax Analysis from Standard Input\n");
        printf("... Type your code and press Ctrl+D (EOF) to parse ...\n\n");
    }

    // Initialize symbol table with predefined types/functions 
    initialize();

    // Run the parser
    yyparse();

    // Check if parsing was successful
    if (syntax_err > 0) {
        printf("\n...Syntax analysis failed with %d errors.\n", syntax_err);
        exit(1);
    } 
    
    printf("\n...Syntax analysis successful.\n");

    // Print the generated Abstract Syntax Tree (AST)
    print_ast(root);
}
